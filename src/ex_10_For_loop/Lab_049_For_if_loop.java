package ex_10_For_loop;

public class Lab_049_For_if_loop {

    static void main(String[] args) {
        for (int i = 0; i<=30; i++)
        {
            if(i>18)
            {
                System.out.println("you can vote");
            }
            else
            {
                System.out.println("you cannot vote");
            }
        }
    }
}
